/**
 * Reports missing, changed, and surplus generated pages without writing files.
 */
export function checkErrorDocs(root = repositoryRoot): string[] {
  const expected = generateErrorDocs()
  const issues: string[] = []
  for (const [path, content] of expected) {
    const absolute = resolve(root, path)
    if (!existsSync(absolute)) {
      issues.push(`Missing: ${path}`)
    } else if (readFileSync(absolute, 'utf8') !== content) {
      issues.push(`Outdated: ${path}`)
    }
  }
  for (const locale of locales) {
    for (const path of markdownFiles(
      resolve(root, `docs${locale.prefix}/errors`),
    )) {
      const local = relative(root, path).replaceAll('\\', '/')
      if (!expected.has(local)) {
        issues.push(`Unexpected: ${local}`)
      }
    }
  }
  return issues
}

/**
 * Builds all generated pages in memory so --check cannot rewrite content.
 */
export function generateErrorDocs(): Map<string, string> {
  const pages = new Map<string, string>()
  for (const locale of locales) {
    validateNotes(locale.notes)
    const index = [
      generatedHeader,
      '',
      `# ${locale.title}`,
      '',
      locale.intro,
      '',
      `[${locale.catching}](${locale.prefix}/guide/errors)`,
      '',
    ]
    for (const [category, title] of Object.entries(locale.categories)) {
      index.push(
        `## ${title}`,
        '',
        `| ${locale.columns.join(' | ')} |`,
        '|---|---|---|---|',
      )
      for (const code of Object.values(ERROR_CODES)) {
        const metadata = ERROR_METADATA[code]
        if (metadata.category !== category) {
          continue
        }
        const diagnosticCode = DIAGNOSTIC_CODES[code]
        const slug = diagnosticCode.toLowerCase()
        const note = locale.notes[code]
        index.push(
          `| [\`${diagnosticCode}\`](${locale.prefix}/errors/${slug}/) | ${note.title} | ${title} | \`${metadata.packageName}\` |`,
        )
      }
      index.push('')
    }
    pages.set(`docs${locale.prefix}/errors/index.md`, index.join('\n'))
    for (const code of Object.values(ERROR_CODES)) {
      const note = locale.notes[code]
      const metadata = ERROR_METADATA[code]
      const example = examples[code]
      const error = sampleError(code)
      const diagnosticCode = DIAGNOSTIC_CODES[code]
      const page = [
        generatedHeader,
        '',
        `# ${diagnosticCode}: ${note.title}`,
        '',
        note.summary,
        '',
        `## ${locale.steps}`,
        '',
        ...note.steps.map((step, i) => `${i + 1}. ${step}`),
        '',
        `## ${locale.before}`,
        '',
        '```ts',
        example.before,
        '```',
        '',
        `## ${locale.after}`,
        '',
        '```ts',
        example.after,
        '```',
        '',
        `## ${locale.causes}`,
        '',
        ...note.causes.map(cause => `- ${cause}`),
        '',
        `## ${locale.fields}`,
        '',
        `- \`code\`: \`${code}\``,
        `- \`diagnosticCode\`: \`${diagnosticCode}\``,
        `- \`name\`: \`DocxKitError\``,
        `- \`docs\`: ${error.docs}`,
        '',
        `### ${locale.message}`,
        '',
        '```text',
        error.message,
        '```',
        '',
        `## ${locale.links}`,
        '',
        `- [${locale.source}](https://github.com/ntnyq/docx-kit/blob/main/${metadata.source})`,
        `- [${locale.guide}](${locale.prefix}${example.guide})`,
        `- [${locale.catching}](${locale.prefix}/guide/errors)`,
        `- [${locale.index}](${locale.prefix}/errors/)`,
        '',
      ]
      pages.set(
        `docs${locale.prefix}/errors/${diagnosticCode.toLowerCase()}/index.md`,
        page.join('\n'),
      )
    }
  }
  return pages
}

function markdownFiles(directory: string): string[] {
  if (!existsSync(directory)) {
    return []
  }
  return readdirSync(directory, { withFileTypes: true }).flatMap(entry => {
    if (entry.name === '_meta') {
      return []
    }
    const path = resolve(directory, entry.name)
    return entry.isDirectory()
      ? markdownFiles(path)
      : entry.name.endsWith('.md')
        ? [path]
        : []
  })
}

function sampleError<Code extends ErrorCode>(code: Code) {
  return createDocxKitError(code, samples[code])
}

function validateNotes(notes: ErrorNotes) {
  const codes = Object.keys(ERROR_CODES)
  if (Object.keys(notes).some(code => !codes.includes(code))) {
    throw new Error('Unknown error code in translated error notes')
  }
  for (const code of Object.values(ERROR_CODES)) {
    const note = notes[code]
    if (
      !note?.title
      || !note.summary
      || !note.steps.length
      || !note.causes.length
      || !examples[code]
      || !samples[code]
    ) {
      throw new Error(`Missing error documentation: ${code}`)
    }
  }
}

if (process.argv[1] && resolve(process.argv[1]) === import.meta.filename) {
  if (process.argv.includes('--check')) {
    const issues = checkErrorDocs()
    if (issues.length) {
      console.error(issues.join('\n'))
      process.exitCode = 1
    } else {
      console.log('Error documentation is synchronized (57 pages).')
    }
  } else {
    for (const [path, content] of generateErrorDocs()) {
      const absolute = resolve(repositoryRoot, path)
      mkdirSync(dirname(absolute), { recursive: true })
      writeFileSync(absolute, content)
    }
    console.log('Generated error documentation (57 pages).')
  }
}
