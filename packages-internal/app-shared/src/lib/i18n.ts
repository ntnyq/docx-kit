export function createAppI18n() {
  const requested = new URLSearchParams(window.location.search).get('lang')
  let saved: string | null = null
  try {
    saved = localStorage.getItem('docx-kit:locale')
  } catch {
    // Preferences are optional when browser storage is unavailable.
  }
  const language = requested ?? saved ?? navigator.language
  const locale = resolveToolLocale(language)
  return createI18n({
    fallbackLocale: 'en-US',
    legacy: false,
    locale,
    messages: {
      'en-US': { ...messagesByLocale['en-US'], ...appMessages['en-US'] },
      'zh-CN': { ...messagesByLocale['zh-CN'], ...appMessages['zh-CN'] },
      'zh-TW': { ...messagesByLocale['zh-TW'], ...appMessages['zh-TW'] },
    },
  })
}
